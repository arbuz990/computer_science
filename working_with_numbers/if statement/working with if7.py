number1 = input('enter a number')
number1 = float(number1)
number2 = input('enter a second number')
number2 = float(number2)
operator = input('enter + - * /')

if operator == '+':
    print(number1 + number2)
    
elif operator == '-':
    print(number1 - number2)
    
elif operator == '*':
    print(number1 * number2)

elif operator =='/':
    print(number1 / number2)


    